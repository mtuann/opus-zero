"""Bản nhạc chép tay cho bài không có nguồn số dùng được.

satie_gymnopedie1: Gymnopédie số 1 (Satie, 1888, phạm vi công cộng), chép theo bản LilyPond của
https://github.com/rileylev/gymnopedie (kho không ghi giấy phép; ở đây chỉ chép cao độ và trường độ của tác phẩm).
Thứ tự chơi: lượt 1 = ô 1–32 + kết 1 (chỉ số 0–38), lượt 2 = ô 1–32 + kết 2 (chỉ số 39–77).
"""
import re

import numpy as np

from scores import Score

NOTE = {"C": 0, "D": 2, "E": 4, "F": 5, "G": 7, "A": 9, "B": 11}


def m(name):
    """'F#5' -> số MIDI."""
    mm = re.match(r"([A-G])([#b]?)(-?\d)", name)
    return 12 * (int(mm.group(3)) + 1) + NOTE[mm.group(1)] + {"#": 1, "b": -1, "": 0}[mm.group(2)]


def build(bars, qsec, beats_per_bar=3):
    """bars: danh sách ô; mỗi ô là danh sách (phách bắt đầu tính từ 0, độ dài theo phách, [tên nốt...])."""
    notes, starts = [], []
    for i, bar in enumerate(bars):
        t0 = i * beats_per_bar * qsec
        starts.append(t0)
        for b, d, ps in bar:
            for p in ps:
                notes.append((t0 + b * qsec, t0 + (b + d) * qsec, m(p), 70))
    return Score(np.array(sorted(notes)), np.array(starts))


def satie_gymnopedie1(qpm=66.0):
    q = 60.0 / (qpm or 66.0)
    acc = {}
    for k in range(1, 17):
        acc[k] = [(0, 3, ["G2"]), (1, 2, ["B3", "D4", "F#4"])] if k % 2 else [(0, 3, ["D2"]), (1, 2, ["A3", "C#4", "F#4"])]
    bass = ["F#2", "B1", "E2", "E2", "D2", "A1"] + ["D2"] * 9 + ["E2"]
    ch = [["A3", "C#4", "F#4"], ["B3", "D4", "F#4"], ["G3", "B3"], ["B3", "D4", "G4"], ["F3", "A3", "D4"], ["A3", "C4", "E4"],
          ["G3", "B3", "E4"], ["D3", "G3", "B3", "E4"], ["C3", "E3", "A3", "D4"], ["C3", "F#3", "A3", "D4"], ["A3", "C4", "F4"],
          ["A3", "C4", "E4"], ["D3", "G3", "B3", "E4"], ["C3", "E3", "A3", "D4"], ["C3", "F#3", "A3", "D4"], ["B3", "E4", "G4"]]
    for i in range(16):
        acc[17 + i] = [(0, 3, [bass[i]]), (1, 2, ch[i])]
    mel = {5: [(1, 1, ["F#5"]), (2, 1, ["A5"])], 6: [(0, 1, ["G5"]), (1, 1, ["F#5"]), (2, 1, ["C#5"])], 7: [(0, 1, ["B4"]), (1, 1, ["C#5"]), (2, 1, ["D5"])],
           8: [(0, 3, ["A4"])], 9: [(0, 12, ["F#4"])],
           13: [(1, 1, ["F#5"]), (2, 1, ["A5"])], 14: [(0, 1, ["G5"]), (1, 1, ["F#5"]), (2, 1, ["C#5"])], 15: [(0, 1, ["B4"]), (1, 1, ["C#5"]), (2, 1, ["D5"])],
           16: [(0, 3, ["A4"])], 17: [(0, 3, ["C#5"])], 18: [(0, 3, ["F#5"])], 19: [(0, 9, ["E4"])],
           22: [(0, 1, ["A4"]), (1, 1, ["B4"]), (2, 1, ["C5"])], 23: [(0, 1, ["E5"]), (1, 1, ["D5"]), (2, 1, ["B4"])], 24: [(0, 1, ["D5"]), (1, 1, ["C5"]), (2, 1, ["B4"])],
           25: [(0, 5, ["D5"])], 26: [(2, 1, ["D5"])], 27: [(0, 1, ["E5"]), (1, 1, ["F5"]), (2, 1, ["G5"])], 28: [(0, 1, ["A5"]), (1, 1, ["C5"]), (2, 1, ["D5"])],
           29: [(0, 1, ["E5"]), (1, 1, ["D5"]), (2, 1, ["B4"])], 30: [(0, 5, ["D5"])], 31: [(2, 1, ["D5"])], 32: [(0, 3, ["G5"])]}
    common = [acc.get(k, []) + mel.get(k, []) for k in range(1, 33)]
    alt1 = [[(0, 3, ["D2"]), (1, 2, ["A3", "C#4", "F#4"]), (0, 3, ["F#5"])],
            [(0, 3, ["B1"]), (1, 2, ["B3", "D4", "F#4"]), (0, 1, ["B4"]), (1, 1, ["A4"]), (2, 1, ["B4"])],
            [(0, 3, ["E2"]), (1, 2, ["C#4", "E4", "A4"]), (0, 1, ["C#5"]), (1, 1, ["D5"]), (2, 1, ["E5"])],
            [(0, 3, ["E2"]), (1, 2, ["A3", "C#4", "F#4", "A4"]), (0, 1, ["C#5"]), (1, 1, ["D5"]), (2, 1, ["E5"])],
            [(0, 3, ["E2"]), (1, 1, ["B2"]), (2, 1, ["E3"]), (0, 3, ["F#4"]), (1, 1, ["A3", "D4"]), (2, 1, ["B3", "D4", "G4"])],
            [(0, 3, ["A2", "G3", "C4", "E4", "A4", "C5"])],
            [(0, 3, ["D2", "A3", "D4", "F#4", "A4", "D5"])]]
    alt2 = [[(0, 3, ["E2"]), (1, 2, ["A3", "D4", "F4", "A4"]), (0, 3, ["F5"])],
            [(0, 3, ["E2"]), (1, 2, ["A3", "C4", "F4"]), (0, 1, ["B4"]), (1, 1, ["C5"]), (2, 1, ["F5"])],
            [(0, 3, ["E2"]), (1, 2, ["C4", "E4", "A4"]), (0, 1, ["E5"]), (1, 1, ["D5"]), (2, 1, ["C5"])],
            [(0, 3, ["E2"]), (1, 2, ["A3", "C4", "F4", "A4"]), (0, 1, ["E5"]), (1, 1, ["D5"]), (2, 1, ["C5"])],
            [(0, 3, ["E2"]), (1, 1, ["B2"]), (2, 1, ["E3"]), (0, 3, ["F4"]), (1, 1, ["A3", "D4"]), (2, 1, ["B3", "D4", "G4"])],
            [(0, 3, ["A2", "G3", "C4", "E4", "A4", "C5"])],
            [(0, 3, ["D2", "A2", "D3", "D4", "F4", "A4", "D5"])]]
    return build(common + alt1 + common + alt2, q)
